CREATE TABLE CLIENTES (
  ID INTEGER NOT NULL PRIMARY KEY,
  NOME VARCHAR(60),
  CIDADE VARCHAR(40),
  ATIVO SMALLINT,
  LIMITE NUMERIC(15,2),
  CADASTRO DATE,
  OBS BLOB SUB_TYPE 1
);
CREATE TABLE PEDIDOS (
  ID INTEGER NOT NULL PRIMARY KEY,
  CLIENTE_ID INTEGER REFERENCES CLIENTES(ID),
  EMISSAO TIMESTAMP,
  HORA TIME,
  VALOR DOUBLE PRECISION,
  QTD BIGINT,
  STATUS CHAR(1)
);
CREATE VIEW V_PEDIDOS AS SELECT P.ID, C.NOME, P.VALOR, P.EMISSAO FROM PEDIDOS P JOIN CLIENTES C ON C.ID = P.CLIENTE_ID;
